async def send_strategy_email(
    to_email: str,
    strategy_data: StrategyEmailData,
) -> bool:
    """构建策略 HTML 并发送邮件。"""
    html_content = build_strategy_html(strategy_data)
    dir_label = get_direction_label(strategy_data.direction, strategy_data.locale)
    _subject_prefix = {
        "zh-CN": "策略更新",
        "zh-TW": "策略更新",
        "en": "Strategy Update",
    }
    locale = strategy_data.locale
    prefix = _subject_prefix.get(locale, _subject_prefix["en"])
    subject = f"[Axiom] {strategy_data.symbol} {prefix} — {dir_label}"
    return await _dispatch_email(to_email, subject, html_content)


