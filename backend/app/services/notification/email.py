# ── 邮件发送底层 ──────────────────────────────────────────────

_DEFAULT_FROM = "noreply@axiom123.cc"


async def _get_email_provider() -> tuple[str, str] | None:
    """获取可用的邮件服务商和 API Key。

    优先级: resend_api_key > sendgrid_api_key
    返回 (provider, api_key) 或 None。
    """
    from app.services.config_service import get_config_value

    resend_key = await get_config_value("resend_api_key")
    if resend_key:
        return ("resend", resend_key)

    sendgrid_key = await get_config_value("sendgrid_api_key")
    if sendgrid_key:
        return ("sendgrid", sendgrid_key)

    return None


async def _send_via_resend(
    api_key: str, from_email: str, to_email: str, subject: str, html_content: str
) -> bool:
    """通过 Resend API 发送邮件。"""
    import resend
    import asyncio as _aio
    resend.api_key = api_key
    last_exc = None
    for attempt in range(3):
        try:
            resp = resend.Emails.send({
                "from": from_email,
                "to": [to_email],
                "subject": subject,
                "html": html_content,
            })
            email_id = resp.get("id") if isinstance(resp, dict) else getattr(resp, "id", None)
            logger.info("Email sent via Resend", extra={"to": to_email, "id": email_id})
            return True
        except Exception as exc:
            last_exc = exc
            if attempt < 2:
                await _aio.sleep(1 * (attempt + 1))
    logger.exception("Failed to send email via Resend after 3 attempts", extra={"to": to_email})
    return False


async def _send_via_sendgrid(
    api_key: str, from_email: str, to_email: str, subject: str, html_content: str
) -> bool:
    """通过 SendGrid API 发送邮件（向后兼容）。"""
    try:
        from sendgrid import SendGridAPIClient
        from sendgrid.helpers.mail import Mail

        message = Mail(
            from_email=from_email,
            to_emails=to_email,
            subject=subject,
            html_content=html_content,
        )
        sg = SendGridAPIClient(api_key)
        response = sg.send(message)
        logger.info("Email sent via SendGrid", extra={"to": to_email, "status": response.status_code})
        return response.status_code in (200, 201, 202)
    except Exception:
        logger.exception("Failed to send email via SendGrid", extra={"to": to_email})
        return False


async def _is_suppressed(email: str) -> bool:
    """检查邮箱是否在抑制列表中（退信/投诉过）。"""
    try:
        from app.core.database import get_db_context
        from sqlalchemy import text as sa_text
        async with get_db_context() as session:
            result = await session.execute(
                sa_text("SELECT 1 FROM email_suppression WHERE email = :email"),
                {"email": email.lower().strip()},
            )
            return result.first() is not None
    except Exception:
        return False


async def _dispatch_email(
    to_email: str, subject: str, html_content: str, from_email: str = _DEFAULT_FROM
) -> bool:
    """统一邮件分发——自动选择可用的服务商。"""
    if await _is_suppressed(to_email):
        logger.info("Email to %s suppressed (bounced/complained), skipping", to_email)
        return False

    provider = await _get_email_provider()
    if provider is None:
        logger.warning("No email provider configured (set resend_api_key or sendgrid_api_key), skipping email")
        return False

    name, api_key = provider
    if name == "resend":
        return await _send_via_resend(api_key, from_email, to_email, subject, html_content)
    return await _send_via_sendgrid(api_key, from_email, to_email, subject, html_content)


