def _get_localized_strings(
    locale: str,
    strings_map: dict[str, dict[str, str]],
) -> dict[str, str]:
    """按 locale 获取邮件本地化字符串。"""
    if locale in strings_map:
        return strings_map[locale]
    if locale.startswith("zh"):
        return strings_map["zh-CN"]
    return strings_map["en"]


def _get_html_lang(locale: str) -> str:
    """将 locale 转换为 HTML lang 属性值。"""
    return {"zh-CN": "zh-CN", "zh-TW": "zh-TW", "en": "en"}.get(locale, "en")


# ── HTML 模板构建 ─────────────────────────────────────────────


def _format_price(price: float) -> str:
    """格式化价格，保留合理小数位。"""
    if price >= 1000:
        return f"{price:,.2f}"
    if price >= 1:
        return f"{price:.4f}"
    return f"{price:.8f}"


def _build_confidence_stars(confidence: float) -> str:
    """将 0-1 置信度转换为星级 HTML。"""
    stars = round(confidence * 5)
    filled = "★" * stars
    empty = "☆" * (5 - stars)
    return f"{filled}{empty}"


def _build_targets_html(targets: list[float], accent: str) -> str:
    """构建目标价列表 HTML。"""
    if not targets:
        return '<span style="color:#666;">—</span>'
    items: list[str] = []
    for i, t in enumerate(targets, 1):
        items.append(
            f'<span style="color:{accent};font-family:\'Roboto Mono\',monospace;">'
            f"T{i}: {_format_price(t)}</span>"
        )
    return " → ".join(items)


